// AUDIT-1 check 1: parameter census. Lists every registry parameter with its value in every preset,
// unit, status (cited / tuned / to-verify) and the reference it names, plus the physical constants
// hard-coded outside the registry (src/engine/constants.ts, cement.ts, runout.ts, failure.ts, ...).
// Usage: node scripts/review/audit-01/params-census.mjs [outfile.md]
// Read-only: imports the engine through vite's SSR loader; changes nothing.
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readFileSync, writeFileSync } from 'node:fs'
import { createServer } from 'vite'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const outFile = process.argv[2]
const server = await createServer({
  root, configFile: false, appType: 'custom', logLevel: 'error',
  server: { middlewareMode: true, hmr: false, watch: null, fs: { strict: false } },
  optimizeDeps: { noDiscovery: true, include: [] },
})
const load = (p) => server.ssrLoadModule(p)
const { PARAMS } = await load('/src/engine/params.ts')
const { PRESETS } = await load('/src/engine/presets.ts')
const { defaultEngineParams } = await load('/src/engine/engineParams.ts')
const Refs = await load('/src/engine/references.ts')

const fmt = (v) => (v === null ? 'null' : Array.isArray(v) ? `[${v.map(fmt).join(', ')}]` : typeof v === 'number' ? (Number.isInteger(v) && Math.abs(v) < 1e6 ? String(v) : v.toExponential(3).replace(/\.?0+e/, 'e')) : String(v))
const ids = PRESETS.map((p) => p.id)
const lines = []
const say = (s = '') => lines.push(s)

say('# Parameter census (AUDIT-1 check 1, generated by scripts/review/audit-01/params-census.mjs)')
say()
say(`Registry: ${PARAMS.length} parameters. Presets: ${ids.join(', ')}. A preset cell shows "=" when it keeps the registry default.`)
say()
const counts = { cited: 0, tuned: 0, 'to-verify': 0 }
const byKind = { cited: [], tuned: [], 'to-verify': [] }
say('| key | label | unit (SI -> display) | default | ' + ids.join(' | ') + ' | status | ref | note (first 110 chars) |')
say('|---|---|---|---|' + ids.map(() => '---').join('|') + '|---|---|---|')
for (const p of PARAMS) {
  counts[p.source.kind]++
  byKind[p.source.kind].push(p.key)
  const cells = PRESETS.map((pr) => (pr.params[p.key] === undefined ? '=' : fmt(pr.params[p.key])))
  const ref = p.source.refId ? (Refs.getReference?.(p.source.refId) ? p.source.refId : `${p.source.refId} (NOT IN references.ts)`) : '-'
  say(`| ${p.key} | ${p.label} | ${p.unit} -> ${p.displayUnit} | ${fmt(p.default)} | ${cells.join(' | ')} | ${p.source.kind} | ${ref} | ${p.source.note.slice(0, 110).replace(/\|/g, '/')}${p.source.note.length > 110 ? '...' : ''} |`)
}
say()
say(`Counts: cited ${counts.cited}, to-verify ${counts['to-verify']}, tuned ${counts.tuned}.`)
say()
say('Cited: ' + byKind.cited.join(', '))
say()
say('To verify: ' + byKind['to-verify'].join(', '))
say()

// registry vs engine defaults: every engine field must be a registry key and vice versa
const eng = defaultEngineParams()
const regKeys = new Set(PARAMS.map((p) => p.key))
const engKeys = Object.keys(eng)
const onlyEng = engKeys.filter((k) => !regKeys.has(k))
const onlyReg = [...regKeys].filter((k) => !(k in eng))
say(`Engine fields not in the registry: ${onlyEng.length ? onlyEng.join(', ') : 'none'}. Registry keys not in EngineParams: ${onlyReg.length ? onlyReg.join(', ') : 'none'}.`)
say()

// preset overrides that name keys outside the registry
for (const pr of PRESETS) {
  const bad = Object.keys(pr.params).filter((k) => !regKeys.has(k))
  if (bad.length) say(`Preset ${pr.id} sets keys outside the registry: ${bad.join(', ')}`)
}

// hard-coded physical numbers outside the registry: scan src/engine for numeric constants with a unit-like comment
say('## Numbers set in engine code outside the registry')
say()
say('Found by scanning `export const` / `const` declarations with numeric literals in src/engine/*.ts (hand-filtered list of the physical ones follows in the audit report).')
say()
const { readdirSync } = await import('node:fs')
const dir = join(root, 'src', 'engine')
for (const f of readdirSync(dir).filter((x) => x.endsWith('.ts')).sort()) {
  const src = readFileSync(join(dir, f), 'utf8').split('\n')
  src.forEach((line, i) => {
    const m = line.match(/^\s*(?:export\s+)?const\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?::[^=]+)?=\s*(-?[0-9][0-9.e+-]*)\s*(?:\/\/.*)?$/)
    if (m) say(`- ${f}:${i + 1} ${m[1]} = ${m[2]}${line.includes('//') ? ' ' + line.slice(line.indexOf('//')).trim() : ''}`)
    const m2 = line.match(/^\s*(?:export\s+)?const\s+([A-Z_]+)\s*=\s*\{.*\}\s*$/)
    if (m2) say(`- ${f}:${i + 1} ${m2[1]} = ${line.trim().slice(line.indexOf('=') + 1).trim()}`)
  })
}
const text = lines.join('\n') + '\n'
if (outFile) writeFileSync(outFile, text)
else process.stdout.write(text)
await server.close()

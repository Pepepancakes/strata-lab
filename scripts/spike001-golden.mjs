// Regenerates tests/golden/spike001-default.json from the READ-ONLY reference engine
// (spikes/001-shelf-to-basin/engine.js): default parameters, 600 steps of 5 kyr.
// Run: node scripts/spike001-golden.mjs
// The port (src/engine) must reproduce these numbers: tests/golden.test.ts.

import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const S = createRequire(import.meta.url)(join(root, 'spikes/001-shelf-to-basin/engine.js'))

const P = S.defaultParams()
const st = S.createState(P)
while (S.step(st, P)) { /* run to the end */ }

const nx = P.nx
const H = [], b = [], sand = [], mud = [], maxU = []
for (let j = 0; j < nx; j++) {
  let s = 0, m = 0, u = 0
  for (let l = 0; l <= st.k; l++) {
    const i = l * nx + j
    s += st.sand[i]
    m += st.mud[i]
    if (st.u[i] > u) u = st.u[i]
  }
  H.push(st.H[j]); b.push(st.b[j]); sand.push(s); mud.push(m); maxU.push(u)
}
const out = {
  note: 'Generated by scripts/spike001-golden.mjs from spikes/001-shelf-to-basin/engine.js. Do not edit by hand.',
  nx, steps: st.k, dtRec: P.dtRec,
  H, b, solidSand: sand, solidMud: mud, maxExcessPorePressure: maxU,
  maxExcessPorePressureAll: Math.max(...maxU),
}
const file = join(root, 'tests/golden/spike001-default.json')
mkdirSync(dirname(file), { recursive: true })
writeFileSync(file, JSON.stringify(out, null, 1) + '\n')
console.log(`wrote ${file}: ${nx} columns, ${st.k} steps`)

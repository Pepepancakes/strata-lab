// Writes src/views/well/bundleTable.ts: for each preset that bundles deep compaction (bundleEvery > 1), how far
// the pore pressure of the bundled run is from the full solve (bundleEvery = 1) below about 5,000 ft under the
// sea floor. Run it by hand after any change to the compaction solver or a bundled preset:
//   node scripts/gen-bundle-table.mjs [presetId ...]     (default: every bundled preset; the Cenozoic full solve takes minutes)
// The numbers are measured here, not typed. Method: both runs end at the same layer set, so a cell index means the
// same cell in both. For every column and every sediment cell more than 5,000 ft below the sea floor in the full
// run, take |u(bundled) - u(full)| / (g * depth below sea surface to the cell middle), in ppg; the table keeps the
// largest, rounded UP to 0.1 ppg so the on-screen note never understates it. Salt cells are skipped (no pore water).
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { writeFileSync } from 'node:fs'
import { createServer } from 'vite'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const server = await createServer({
  root, configFile: false, appType: 'custom', logLevel: 'error',
  server: { middlewareMode: true, hmr: false, watch: null, fs: { strict: false } },
  optimizeDeps: { noDiscovery: true, include: [] },
})
const load = (p) => server.ssrLoadModule(p)
const S = await load('/src/engine/step.ts')
const Pr = await load('/src/engine/presets.ts')
const Sea = await load('/src/engine/sealevel.ts')
const Comp = await load('/src/engine/compaction.ts')
const K = await load('/src/engine/constants.ts')
const Rec = await load('/src/engine/record.ts')
const U = await load('/src/units.ts')

const FT = 0.3048
const DEPTH_FROM_FT = 5000
const wanted = process.argv.slice(2)
const ids = (wanted.length ? wanted : Pr.PRESETS.map((p) => p.id)).filter((id) => Pr.presetParams(id).bundleEvery > 1)

function run(id, bundleEvery) {
  const P = { ...Pr.presetParams(id), bundleEvery }
  const sch = Pr.presetSchedule(id)
  const eng = S.createEngine(P, sch)
  const sea = Sea.makeSeaLevel(P, sch.startAgeMa * 1e6)
  while (S.step(eng, P, sch, sea)) { /* run to the end */ }
  return { P, eng, seaEnd: sea(sch.tEndYr[sch.nSteps - 1]) }
}

const entries = {}
for (const id of ids) {
  const N = Pr.presetParams(id).bundleEvery
  const t0 = Date.now()
  const a = run(id, N)
  const b = run(id, 1)
  const rec = b.eng.rec, nx = rec.nx
  let worst = 0, worstCol = -1, cells = 0
  for (let j = 0; j < nx; j++) {
    const wd = Math.max(0, b.seaEnd - rec.H[j])
    let depth = wd
    for (let l = rec.nLayers - 1; l >= 0; l--) {
      const i = l * nx + j
      if (rec.sand[i] + rec.mud[i] <= 1e-9) continue
      const h = Comp.cellBulk(b.eng, b.P, i)
      const mid = depth + 0.5 * h
      depth += h
      if (rec.material[i] === Rec.SALT) continue
      if ((mid - wd) / FT < DEPTH_FROM_FT) continue
      cells++
      const d = Math.abs(U.densityToPpg(a.eng.rec.u[i] / (K.G * mid)) - U.densityToPpg(rec.u[i] / (K.G * mid)))
      if (d > worst) { worst = d; worstCol = j }
    }
  }
  entries[id] = { bundleEvery: N, maxPpg: Math.ceil(worst * 10 - 1e-9) / 10, rawPpg: Number(worst.toFixed(3)), column: worstCol, cells }
  console.log(`${id}: bundled x${N} vs full, worst ${worst.toFixed(3)} ppg at col ${worstCol} over ${cells} cells (${((Date.now() - t0) / 1000).toFixed(0)} s)`)
}

const lines = [
  '// GENERATED by scripts/gen-bundle-table.mjs. Do not edit by hand: change the script and run it again.',
  '// What it holds: for each preset that bundles deep compaction, the largest pore-pressure difference, in ppg,',
  '// between the bundled run and the full solve (bundleEvery = 1) in any cell more than 5,000 ft below the sea floor,',
  '// at the end of the run. Rounded up to 0.1 ppg. Source: AUDIT-1 finding F-1, remeasured by the script.',
  '',
  'export const BUNDLE_TABLE_PROVENANCE = \'measured by scripts/gen-bundle-table.mjs: bundled vs full solve, all columns, cells deeper than 5,000 ft below the sea floor, end of run (AUDIT-1 F-1)\'',
  '',
  'export interface BundleEntry {',
  '  /** The preset\'s own bundleEvery when measured. */',
  '  bundleEvery: number',
  '  /** Largest |pore pressure, bundled minus full|, ppg, rounded up to 0.1. */',
  '  maxPpg: number',
  '  /** The same before rounding, and where it was found (column index), for the record. */',
  '  rawPpg: number',
  '  column: number',
  '  cells: number',
  '}',
  '',
  'export const BUNDLE_TABLE: Readonly<Record<string, BundleEntry>> = ' + JSON.stringify(entries, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'") + '',
  '',
]
writeFileSync(join(root, 'src', 'views', 'well', 'bundleTable.ts'), lines.join('\n'))
console.log('wrote src/views/well/bundleTable.ts')
await server.close()
